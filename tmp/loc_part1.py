def write_xml(folder, mapping):
    out_dir = os.path.join("app/src/main/res", folder)
    os.makedirs(out_dir, exist_ok=True)
    out_path = os.path.join(out_dir, "strings.xml")
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
    for k, v in mapping.items():
        escaped = saxutils.escape(v).replace("'", "\\'")
        lines.append(f'    <string name="{k}">{escaped}</string>')
    lines.append('</resources>')
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

if __name__ == "__main__":
    base_keys = list(LOCALES["values"].keys())
    for folder, mapping in LOCALES.items():
        missing = [k for k in base_keys if k not in mapping]
        if missing:
            raise SystemExit(f"Missing keys in {folder}: {missing}")
        write_xml(folder, mapping)
    print(f"Wrote {len(LOCALES)} locale files with {len(base_keys)} keys each.")
